// Generates the portfolio v2 content migration from projects.mjs and experience.mjs.
// Usage: node scripts/build-content-migration.ts > supabase/migrations/<timestamp>_content.sql
import { projects, retiredProjects } from '../src/content/projects.ts';
import { experience } from '../src/content/experience.ts';

const q = (v: unknown) => (v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a?: string[] | null) => (a?.length ? `array[${a.map(q).join(', ')}]::text[]` : `'{}'::text[]`);
const json = (v: unknown) => `${q(JSON.stringify(v ?? []))}::jsonb`;

const out: string[] = [];
out.push('-- Portfolio v2 content. Generated by scripts/build-content-migration.ts; edit src/content, not this.');
out.push('begin;');
out.push('');
out.push('-- Retire older practice projects (kept, just hidden).');
out.push(`update public.projects set is_visible = false, featured = false where name in (${retiredProjects.map(q).join(', ')});`);
out.push('');

projects.forEach((p, i) => {
  const cols: Record<string, string> = {
    slug: q(p.slug),
    name: q(p.name),
    tagline: q(p.tagline),
    description: q(p.description),
    overview: q(p.overview),
    category: q(p.category),
    platforms: arr(p.platforms),
    role: q(p.role),
    year: q(p.year),
    link: q(p.link ?? ''),
    repo_url: q(p.repo),
    image_url: q(p.cover),
    gallery: json(p.gallery),
    highlights: arr(p.highlights),
    tags: arr(p.stack),
    accent: q(p.accent),
    featured: p.featured ? 'true' : 'false',
    is_visible: 'true',
    display_order: String(i + 1),
  };
  const names = Object.keys(cols);
  // Match existing rows by name first (old rows have no slug), then upsert on slug.
  const match = [p.name, ...(p.aliases ?? [])].map(q).join(', ');
  out.push(`-- ${p.name}`);
  out.push(
    `update public.projects set ${names.map((n) => `${n} = ${cols[n]}`).join(', ')}\n  where slug = ${q(p.slug)} or (slug is null and name in (${match}));`,
  );
  out.push(
    `insert into public.projects (${names.join(', ')})\n  select ${names.map((n) => cols[n]).join(', ')}\n  where not exists (select 1 from public.projects where slug = ${q(p.slug)});`,
  );
  out.push('');
});

out.push('-- Work experience: replace with the current, reconciled history.');
out.push('delete from public.work_experiences;');
experience.forEach((e, i) => {
  out.push(
    `insert into public.work_experiences (company, role, period, location, company_url, summary, description, skills, display_order) values (${[
      q(e.company),
      q(e.role),
      q(e.period),
      q(e.location),
      q(e.url),
      q(e.summary),
      arr(e.points),
      arr(e.skills),
      String(i + 1),
    ].join(', ')});`,
  );
});
out.push('');
out.push('commit;');
console.log(out.join('\n'));
